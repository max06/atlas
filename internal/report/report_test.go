func subset(selected ...string) classify.Result {
	s := append([]string{}, selected...)
	return classify.Result{Mode: "subset", Selected: s, SelectedPR: &s, SelectedBaseline: &s, PRTotal: 10, BaseTotal: 10,
		Changes: []classify.Change{}, OneSideOnly: &[]string{}}
}

func TestShadow(t *testing.T) {
	c := subset("group1/cluster2|dep")
	if r := Shadow([]string{"group1/cluster2/dep/rel"}, c); r.Result != ShadowCovered {
		t.Fatalf("grouped cluster path: %+v", r)
	}
	r := Shadow([]string{"group1/cluster2/dep/rel", "c1/other/rel", "c1/other/rel2"}, c)
	if r.Result != ShadowUncovered || len(r.Missed) != 1 || r.Missed[0] != "c1|other" {
		t.Fatalf("miss: %+v", r)
	}
	if !strings.Contains(r.Markdown, "> - `c1` / `other`") {
		t.Fatalf("markdown:\n%s", r.Markdown)
	}
	if r := Shadow(nil, classify.Result{Mode: "full", Reason: "x"}); r.Result != ShadowFull {
		t.Fatalf("full: %+v", r)
	}
}

func TestScope(t *testing.T) {
	c := subset("c1|dep")
	scope, sh := Scope(ScopeInput{SubsetMode: "shadow", RenderMode: "full", PRStatus: "success", BaselineStatus: "success",
		Classify: &c, Affected: []string{"c1/other/rel"}})
	if sh == nil || sh.Result != ShadowUncovered {
		t.Fatalf("shadow: %+v", sh)
	}
	for _, want := range []string{"**Render scope:** full render (changed-file subsetting runs in shadow mode).",
		"<summary>Shadow: the classifier would have rendered 1 of 10 deployments</summary>", "Subset shadow check FAILED"} {
		if !strings.Contains(scope, want) {
			t.Errorf("scope lacks %q:\n%s", want, scope)
		}
	}
	_, sh = Scope(ScopeInput{SubsetMode: "on", RenderMode: "full", PRStatus: "error", BaselineStatus: "success", Classify: &c})
	if sh.Result != ShadowInconclusive {
		t.Fatalf("failed side: %+v", sh)
	}
	_, sh = Scope(ScopeInput{SubsetMode: "on", RenderMode: "subset", PRStatus: "success", BaselineStatus: "success", Classify: &c})
	if sh.Result != ShadowSkipped {
		t.Fatalf("subset render: %+v", sh)
	}
	if s, sh := Scope(ScopeInput{SubsetMode: "off", Classify: &c}); s != "" || sh != nil {
		t.Fatalf("off: %q %+v", s, sh)
	}
}

func TestBlocksTruncation(t *testing.T) {
	big := strings.Repeat("x", CommentLimit/2)
	var d snapshot.DiffResult
	for _, name := range []string{"a", "b", "c"} {
		d.Releases = append(d.Releases, snapshot.ReleaseDiff{Path: "c/d/" + name,
			Resources: []snapshot.ResourceDiff{{Label: "ConfigMap/" + name, Text: big}}})
	}
	b := Blocks(d)
	if !b.Truncated || !strings.Contains(b.Comment, "c / d / c (1 resources, truncated)") {
		t.Fatalf("truncation missing: %v", b.Truncated)
	}
	if strings.Contains(b.Summary, "truncated") || len(b.Summary) < 3*len(big) {
		t.Fatal("the summary carries every block")
	}
	if len(b.Comment) > CommentLimit {
		t.Fatalf("comment blocks %d > %d", len(b.Comment), CommentLimit)
	}
}

func TestCommentPins(t *testing.T) {
	base := CommentInput{BaselineStatus: "success", PRStatus: "success", DiffStatus: "no-changes", BaselineFilter: true, PRFilter: true}
	in := base
	in.WorkflowPinMerge, in.LatestTag = "v0.7.0", "v0.8.0"
	if !strings.Contains(Comment(in), "pinned to `@v0.7.0`; the latest release is `@v0.8.0`") {
		t.Fatal("older release note missing")
	}
	in = base
	in.WorkflowPinMerge, in.LatestTag = "v0.8.0", "v0.8.0"
	if body := Comment(in); strings.Contains(body, "[!NOTE]") {
		t.Fatalf("the latest release is silent:\n%s", body)
	}
	in = base
	in.WorkflowPinMerge, in.LatestTag = "main", "v0.8.0"
	if body := Comment(in); !strings.Contains(body, "development branch. Pin a release (`@v0.8.0`)") {
		t.Fatalf("main note missing:\n%s", body)
	}
	in = base
	in.WorkflowPinMerge = "0123456789abcdef0123456789abcdef01234567"
	if body := Comment(in); strings.Contains(body, "[!NOTE]") || strings.Contains(body, "[!WARNING]") {
		t.Fatalf("a commit pin is silent:\n%s", body)
	}
	in = base
	in.WorkflowPinMerge, in.WorkflowPinTarget = "v0.8.0", "v0.7.0"
	if body := Comment(in); !strings.Contains(body, "changes the ATLAS review reference: `@v0.7.0` → `@v0.8.0`") || strings.Contains(body, "[!WARNING]") {
		t.Fatalf("pin change:\n%s", body)
	}
	if !strings.HasSuffix(Comment(base), "*Generated by [ATLAS](https://github.com/max06/atlas) Review*\n") {
		t.Fatal("footer")
	}
}

func TestCommentEngines(t *testing.T) {
	base := CommentInput{BaselineStatus: "success", PRStatus: "success", DiffStatus: "no-changes", BaselineFilter: true, PRFilter: true}
	in := base
	in.EngineTarget, in.EngineMerge = "0.13", "0.13"
	if body := Comment(in); strings.Contains(body, "[!NOTE]") {
		t.Fatalf("the same engine on both sides is silent:\n%s", body)
	}
	in.EngineTarget, in.EngineMerge = "0.13", "0.14"
	if body := Comment(in); !strings.Contains(body, "changes the ATLAS engine (atlas.yaml): `0.13` → `0.14`") {
		t.Fatalf("engine change note missing:\n%s", body)
	}
	in.EngineTarget = ""
	if body := Comment(in); !strings.Contains(body, "(atlas.yaml): none → `0.14`") {
		t.Fatalf("first pin note missing:\n%s", body)
	}
	if s := Summary(in); !strings.Contains(s, "| Engine of the merge result (atlas.yaml) | `0.14` |") || !strings.Contains(s, "| Engine of the target branch (atlas.yaml) | — |") {
		t.Fatalf("summary engine rows missing:\n%s", s)
	}
}
